import { createHash } from 'node:crypto'

/**
 * Makes the built app installable (a PWA), with no dependency.
 *
 * At build time it writes two files beside index.html and links them from it:
 *
 *   manifest.webmanifest — the app's name, icons and colours, and where it
 *     starts. Start and scope are relative, so they are this app's own folder
 *     wherever it is deployed.
 *   sw.js — a service worker holding one copy of the app's own files (the
 *     "shell"), so the app opens at once and survives a flaky connection.
 *
 * What the service worker will not do, on purpose:
 *
 *   - It never answers a request to another origin. Everything from Supabase
 *     goes to the network, always: that is private data, and it is never
 *     written to a cache.
 *   - It never reaches outside its own folder. Sibling apps are served from
 *     the same origin, so its cache names carry this app's id and it only
 *     ever deletes its own.
 *   - It never replaces a running app under someone. A new build waits until
 *     the page asks for it (`skip-waiting`, sent from the "new version"
 *     prompt) or every tab has closed. The one exception is a version that
 *     is serving a page it cannot load: that is replaced at once.
 *   - It never prefers its stored page to the real one. A page load goes to
 *     the network first; the stored page is for when there is no network.
 *
 * `passthrough` lists path prefixes (relative to the app's folder) whose page
 * loads are left to the network: public pages that must never be served a
 * cached shell.
 *
 * It also shows push notifications (see push-send): the payload says what to
 * show and which page of the app a tap opens, always inside the worker's own
 * folder. A tap focuses an open window of the app and asks it to go there —
 * no reload — or opens one. Installed, the app's icon wears the unread count.
 *
 * Icons are expected in public/icons: icon-192.png, icon-512.png (both also
 * used as maskable, so keep the artwork inside the middle 80%),
 * apple-touch-icon.png, and badge-96.png — a white silhouette on transparent,
 * which Android draws in the status bar.
 */
export function pwa({ id, name, shortName, description, themeColor, backgroundColor, passthrough = [] }) {
  let base = '/'
  const icons = ['icons/icon-192.png', 'icons/icon-512.png', 'icons/apple-touch-icon.png', 'icons/badge-96.png']

  return {
    name: 'pwa',
    apply: 'build',
    // After Vite has written index.html into the bundle, so it can be listed.
    enforce: 'post',
    configResolved(config) { base = config.base },

    transformIndexHtml: () => [
      { tag: 'link', attrs: { rel: 'manifest', href: `${base}manifest.webmanifest` }, injectTo: 'head' },
      { tag: 'meta', attrs: { name: 'theme-color', content: themeColor }, injectTo: 'head' },
      { tag: 'link', attrs: { rel: 'apple-touch-icon', href: `${base}icons/apple-touch-icon.png` }, injectTo: 'head' },
      { tag: 'meta', attrs: { name: 'apple-mobile-web-app-title', content: shortName }, injectTo: 'head' },
    ],

    generateBundle(_options, bundle) {
      const manifest = {
        name, short_name: shortName, description,
        start_url: './', scope: './', display: 'standalone',
        theme_color: themeColor, background_color: backgroundColor,
        icons: [
          { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
          { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
          { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
        ],
      }
      this.emitFile({ type: 'asset', fileName: 'manifest.webmanifest', source: JSON.stringify(manifest, null, 2) })

      // './' is index.html, the answer to every page load inside the app.
      const built = Object.keys(bundle).filter((f) => f !== 'index.html' && !f.endsWith('.map'))
      const files = ['./', ...built, ...icons, 'manifest.webmanifest']
      const html = bundle['index.html']?.source ?? ''
      const version = createHash('sha256')
        .update(JSON.stringify(files)).update(String(html)).update(JSON.stringify(manifest))
        .digest('hex').slice(0, 12)

      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorker({ id, name, version, files, passthrough }) })
    },
  }
}

const serviceWorker = ({ id, name, version, files, passthrough }) => `// Generated by vite.pwa — do not edit.
const NAME = ${JSON.stringify(name)}
const PREFIX = ${JSON.stringify(`${id}-`)}
const CACHE = PREFIX + ${JSON.stringify(version)}
const FILES = ${JSON.stringify(files)}
const PASSTHROUGH = ${JSON.stringify(passthrough)}

// 'reload' goes past the browser's HTTP cache. The host lets a page be reused
// for ten minutes, and a copy of index.html from before a deploy names scripts
// the deploy has removed: stored here, it would be a blank page for good.
self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(FILES.map((file) => new Request(file, { cache: 'reload' }))))
      .then(brokenShell)
      .then((broken) => {
        if (!broken) return
        // The version in charge is serving a page it cannot load. Take over
        // now rather than wait to be asked: nobody can press Reload on a
        // blank page.
        healing = true
        return self.skipWaiting()
      }))
})

// Whether an older cache of this app holds a page whose scripts or styles are
// not in it — a build that can only ever render blank.
let healing = false
async function brokenShell() {
  const scope = self.registration.scope
  const keys = (await caches.keys()).filter((k) => k.startsWith(PREFIX) && k !== CACHE)
  for (const key of keys) {
    const cache = await caches.open(key)
    const shell = await cache.match(scope)
    if (!shell) continue
    const html = await shell.text()
    const refs = [...html.matchAll(/(?:src|href)="([^"]+\\.(?:js|css))"/g)].map((m) => new URL(m[1], scope).href)
    for (const ref of refs) if (!(await cache.match(ref))) return true
  }
  return false
}

// Only this app's older caches: sibling apps share the origin.
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(
        keys.filter((k) => k.startsWith(PREFIX) && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
      .then(() => healing && self.clients.matchAll({ type: 'window' }))
      .then((windows) => { for (const w of windows || []) w.navigate(w.url) }))
})

self.addEventListener('message', (event) => {
  if (event.data === 'skip-waiting') self.skipWaiting()
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  const scope = self.registration.scope
  // Anything that is not a read of this app's own folder is none of our
  // business: it goes to the network untouched, and is never cached.
  if (request.method !== 'GET' || !request.url.startsWith(scope)) return
  const path = request.url.slice(scope.length)

  if (request.mode === 'navigate') {
    if (PASSTHROUGH.some((prefix) => path.startsWith(prefix))) return
    // The page itself is asked of the network first, revalidated rather than
    // reused, so a deploy shows on the next load and a stored page is never
    // preferred to the real one. The stored copy answers when there is no
    // network, and for an address the host has no file for (a deep link).
    const stored = () => caches.open(CACHE).then((cache) => cache.match(scope))
    event.respondWith(
      fetch(request.url, { cache: 'no-cache' })
        .then((response) => (response.ok ? response : stored().then((hit) => hit || response)))
        .catch(() => stored().then((hit) => hit || Response.error())))
    return
  }
  event.respondWith(
    caches.open(CACHE).then((cache) => cache.match(request)).then((hit) => hit || fetch(request)))
})

// ---------------------------------------------------------------------------
// Push notifications

// A page of this app, never anywhere else: whatever a payload names is read
// against the worker's own folder, and a public page is not a destination.
function appUrl(path) {
  const scope = self.registration.scope
  try {
    const url = new URL(path || '', scope).href
    const inside = url.startsWith(scope) && !PASSTHROUGH.some((p) => url.slice(scope.length).startsWith(p))
    return inside ? url : scope
  } catch {
    return scope
  }
}

function setBadge(count) {
  const nav = self.navigator
  if (!nav || !('setAppBadge' in nav)) return Promise.resolve()
  return (count > 0 ? nav.setAppBadge(count) : nav.clearAppBadge()).catch(() => {})
}

self.addEventListener('push', (event) => {
  let data = {}
  try {
    data = event.data ? event.data.json() : {}
  } catch {
    data = { body: event.data ? event.data.text() : '' }
  }
  const scope = self.registration.scope
  // Every push shows a notification: Safari withdraws permission from a site
  // whose pushes show nothing, and Chrome shows its own in their place.
  event.waitUntil(Promise.all([
    self.registration.showNotification(data.title || NAME, {
      body: data.body || '',
      // One per ticket: a newer one replaces it, and still alerts.
      tag: data.tag || undefined,
      renotify: Boolean(data.tag),
      icon: scope + 'icons/icon-192.png',
      badge: scope + 'icons/badge-96.png',
      timestamp: Date.now(),
      data: { url: appUrl(data.path), id: data.id || null },
    }),
    typeof data.unread === 'number' ? setBadge(data.unread) : null,
    // An open window refreshes its bell at once.
    self.clients.matchAll({ type: 'window' })
      .then((windows) => { for (const w of windows) w.postMessage({ type: 'push', id: data.id || null }) }),
  ]))
})

self.addEventListener('notificationclick', (event) => {
  event.notification.close()
  const url = appUrl(event.notification.data && event.notification.data.url)
  const scope = self.registration.scope
  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((windows) => {
      // A window already running the app (not one of its public pages) goes
      // there itself, without reloading; otherwise a new one opens.
      const open = windows.find((w) => appUrl(w.url) === w.url || w.url === scope)
      if (open) {
        open.postMessage({ type: 'open', url })
        return open.focus()
      }
      return self.clients.openWindow(url)
    }))
})
`
